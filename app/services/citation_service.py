
import re
from typing import Any


# Matches citation references such as [S1], [S2], [S15].
CITATION_PATTERN = re.compile(r"\[(S\d+)\]")


class CitationValidationError(ValueError):
    """Raised when an answer contains invalid source citations."""


class MissingCitationError(CitationValidationError):
    """Raised when an answer has no citations but citations are required."""


def validate_citations(
    answer: str,
    sources: list[dict],
    require_citations: bool = True,
) -> list[dict]:
    """
    Validate Gemini-generated citations against retrieved source metadata.

    Args:
        answer: Text generated by Gemini.
        sources: Source metadata returned by the context builder.
        require_citations: Whether at least one citation is mandatory.

    Returns:
        A list of unique, validated source metadata dictionaries
        in the order they appear in the answer.

    Raises:
        ValueError: If the answer or source metadata is malformed.
        MissingCitationError: If citations are required but absent.
        CitationValidationError: If the answer references an unknown source.
    """

    # 1. Validate the answer.
    if not isinstance(answer, str) or not answer.strip():
        raise ValueError("Answer must be a non-empty string.")

    # 2. Validate the source metadata collection.
    if not isinstance(sources, list):
        raise ValueError("Sources must be a list.")

    source_lookup: dict[str, dict[str, Any]] = {}

    for source in sources:

        if not isinstance(source, dict):
            raise ValueError("Each source must be a dictionary.")

        source_id = source.get("source_id")

        if not isinstance(source_id, str):
            raise ValueError("Every source must have a valid source_id.")

        if not re.fullmatch(r"S\d+", source_id):
            raise ValueError(
                f"Invalid source ID in metadata: {source_id}"
            )

        if source_id in source_lookup:
            raise ValueError(
                f"Duplicate source ID in metadata: {source_id}"
            )

        source_lookup[source_id] = source

    # 3. Extract citation IDs from Gemini's answer.
    citation_ids = CITATION_PATTERN.findall(answer)

    if not citation_ids:
        if require_citations:
            raise MissingCitationError(
                "The generated answer does not contain any citations."
            )

        return []

    # 4. Check that every citation exists in retrieved metadata.
    unknown_ids = list(
        dict.fromkeys(
            source_id
            for source_id in citation_ids
            if source_id not in source_lookup
        )
    )

    if unknown_ids:
        raise CitationValidationError(
            "Answer contains unknown citations: "
            + ", ".join(f"[{source_id}]" for source_id in unknown_ids)
        )

    # 5. Return unique validated sources in answer order.
    validated_sources = []
    seen_ids = set()

    for source_id in citation_ids:

        if source_id in seen_ids:
            continue

        validated_sources.append(
            dict(source_lookup[source_id])
        )

        seen_ids.add(source_id)

    return validated_sources
